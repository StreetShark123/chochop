export const LANGS = ['es', 'gl', 'en'];
const KEY = 'chochop.lang';

function initialLang() {
  try { const s = localStorage.getItem(KEY); if (LANGS.includes(s)) return s; } catch {}
  for (const l of navigator.languages || [navigator.language || '']) {
    const p = l.toLowerCase().slice(0, 2);
    if (p === 'gl') return 'gl';
    if (p === 'es' || p === 'ca' || p === 'eu') return 'es';
    if (p === 'en') return 'en';
  }
  return 'es';
}

let lang = initialLang();
const listeners = [];

export const getLang = () => lang;

export function t(key, vars = {}) {
  const d = dict[lang];
  let s = d[key];
  if (s == null && vars.n != null) s = d[`${key}_${vars.n === 1 ? 'one' : 'other'}`];
  if (s == null) s = dict.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  document.title = `chop chop · ${t('tag')}`;
  document.querySelector('meta[name=description]')?.setAttribute('content', t('metaDesc'));
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-lang]').forEach((el) => el.setAttribute('aria-pressed', String(el.dataset.lang === lang)));
}

export function setLang(l) {
  if (!LANGS.includes(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  applyI18n();
  listeners.forEach((fn) => fn(l));
}

export const onLangChange = (fn) => listeners.push(fn);
